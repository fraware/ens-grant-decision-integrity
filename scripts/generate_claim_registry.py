def claim(
    claim_id: str,
    *,
    title: str,
    proposition: str,
    module: str,
    profiles: list[str],
    checks: list[str],
    evidence: list[str],
    does_not: list[str],
    trust: list[str] | None = None,
    aliases: list[str] | None = None,
    notes: str | None = None,
    status: str = "active",
) -> dict:
    item = {
        "claimId": claim_id,
        "claimVersion": "1",
        "title": title,
        "proposition": proposition,
        "module": module,
        "profileVersions": profiles,
        "requiredChecks": checks,
        "requiredEvidence": evidence,
        "trustAssumptions": trust or [],
        "doesNotEstablish": does_not,
        "status": status,
    }
    if aliases:
        item["aliases"] = aliases
    if notes:
        item["notes"] = notes
    return item


