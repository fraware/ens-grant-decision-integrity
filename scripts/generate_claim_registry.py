def main() -> None:
    ids = [item["claimId"] for item in CLAIMS]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate claim IDs")
    out = {"registryVersion": "1", "claims": CLAIMS}
    path = ROOT / "claims" / "claim-registry.v1.json"
    path.write_bytes((json.dumps(out, indent=2, ensure_ascii=False) + "\n").encode("utf-8"))
    print(f"wrote {path} ({len(CLAIMS)} claims)")


if __name__ == "__main__":
    main()
